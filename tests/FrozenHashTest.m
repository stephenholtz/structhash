classdef FrozenHashTest < matlab.unittest.TestCase
    % The hashes below came from Jan Simon's unmodified DataHash (File Exchange 1.7.1, hash version 4) under Java,
    % MATLAB R2025a. They name recorded trial folders, so they must never change: run this with and without a
    % Java runtime (matlab -nojvm) after any edit.
    %
    %   results = runtests('tests');

    properties (Constant)
        expected = { ...
            'acc0efebdde22a4e5e0ff46e5020803c', ...
            '05ed4cce5394b44781ed08c185658a4b', ...
            'bf9d70617276e591c634fc08cfb1fd7a', ...
            'ec9c4e8c08cf5bbaba37fd6b7ccda3a4', ...
            '71ac28c88ac5f0416a79fc5ccb46f81e', ...
            'ac8a01ce8a2a536cd7930f836af3a5a5', ...
            'eac6a7dae58f687e4d679e517987a8f8', ...
            '36e1c210634425ce9d9717ebbd40ec36', ...
            'dc95c64e7ecc339b1606fcc15b3d2ce7', ...
            '397458289d5e309f7041823b05befae4', ...
            '5e25b13b175f4b8414b7a9ed919ba4d7'}
    end

    methods (Static)
        function in = inputs()
            % stimulus-like structs, as the rig code hashes them: struct(func=..., args=...). The zeros lengths
            % straddle MD5's padding and 64-byte block boundaries.
            in = { ...
                struct('func', 'stims.piezo.step', 'args', struct('amp_um', 1, 'dur_s', 0.5, 'pre_s', 1, 'post_s', 1)), ...
                struct('func', 'stims.ephys.currentStep', 'args', struct('amp_pA', [-20 -10 0 10 20], 'dur_s', 0.2, 'label', "iv")), ...
                struct('func', 'x', 'args', struct()), ...
                struct('func', 'x', 'args', struct('a', [], 'b', '', 'c', {{1, 'two', [3 4 5]}}, 'd', true, 'e', single(2.5), 'f', int16(-7))), ...
                struct('func', 'chirp', 'args', struct('wave', (1:5000) / 7, 'fs', 40000, 'nested', struct('k', uint8(1:200), 's', 'long string here'))), ...
                struct('func', 'x', 'args', struct('v', zeros(1, 7))), ...
                struct('func', 'x', 'args', struct('v', zeros(1, 8))), ...
                struct('func', 'x', 'args', struct('v', zeros(1, 55))), ...
                struct('func', 'x', 'args', struct('v', zeros(1, 56))), ...
                'a char vector', ...
                1:10};
        end

        function print()
            % FrozenHashTest.print: the hashes of inputs(), to paste into expected (only from a trusted DataHash)
            in = FrozenHashTest.inputs();
            for i = 1:numel(in)
                fprintf('            ''%s'', ...\n', DataHash(in{i}));
            end
        end
    end

    methods (TestClassSetup)
        function addDataHash(testCase)
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture(fileparts(fileparts(mfilename('fullpath')))));
        end
    end

    methods (Test)
        function hashVersionIsFour(testCase)
            v = DataHash();
            testCase.verifyEqual(v.HashVersion, 4);
        end

        function hashesAreFrozen(testCase)
            in = FrozenHashTest.inputs();
            testCase.assertNumElements(testCase.expected, numel(in));
            for i = 1:numel(in)
                testCase.verifyEqual(DataHash(in{i}), testCase.expected{i}, sprintf('input %d', i));
            end
        end
    end
end
